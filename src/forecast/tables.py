"""Storm confusion tables per lead day, every model (reports/forecast/storm_tables.md).

"Storm day" = daily max Kp ≥ 5− (G1+). A regression model "warns" when its forecast max Kp reaches that line; the
storm classifier warns when its storm chance passes its tuned threshold (D-48). NOAA is absent: its archived
forecasts contain Ap only, no max Kp.

    python -m src.forecast.tables
"""
import pandas as pd

from src import config, scorecard

NAMES = {"storm_warning": "Storm warning (classifier)", "histgb": "HistGB", "arimax": "ARIMAX", "arima": "ARIMA",
         "sarima": "SARIMA", "chronos": "Chronos", "persistence": "persistence", "recurrence27": "recurrence",
         "trailing27": "27-day average", "climatology": "climatology"}
METRICS = config.FORECAST_REPORTS_DIR / "metrics"
OUT = config.FORECAST_REPORTS_DIR / "storm_tables.md"


def _load(period: str) -> pd.DataFrame:
    parts = [pd.read_csv(METRICS / f"{period}_storms.csv")]
    chronos = config.FORECAST_REPORTS_DIR / f"chronos_{period}_forecasts.csv.gz"
    if chronos.exists() and "chronos" not in set(parts[0]["model"]):
        parts.append(scorecard.storm_table(pd.read_csv(chronos).assign(model="chronos")))
    warn = METRICS / f"{period}_storm_warning.csv"
    if warn.exists():
        parts.append(pd.read_csv(warn))
    t = pd.concat(parts, ignore_index=True)
    return t[t["model"].isin(NAMES)]


def _fmt(x, pct=True):
    if pd.isna(x):
        return "—"
    return f"{x:.0%}" if pct else f"{x + 0.0:.2f}".replace("-0.00", "0.00")


def markdown(t: pd.DataFrame, lead: int) -> str:
    g = t[t["lead"] == lead].copy()
    g["order"] = g["hss"].fillna(-9)
    g = g.sort_values(["order", "hits"], ascending=False)
    best = g["hss"].max()
    lines = ["| Model | Caught | Missed | False alarm | Correct quiet | Detection rate | False-alarm ratio | Heidke skill |",
             "|---|---|---|---|---|---|---|---|"]
    for _, r in g.iterrows():
        name = NAMES[r["model"]]
        name = f"**{name}**" if r["hss"] == best else name
        lines.append(f"| {name} | {int(r['hits'])} | {int(r['misses'])} | {int(r['false_alarms'])} | "
                     f"{int(r['correct_negatives'])} | {_fmt(r['pod'])} | {_fmt(r['far'])} | {_fmt(r['hss'], False)} |")
    return "\n".join(lines)


def main() -> str:
    sections = ["# Storm confusion tables by lead day",
                "",
                "Storm day = daily max Kp ≥ 5− (G1+). Bold = best Heidke skill for that day. NOAA is not included: "
                "its archived forecasts have Ap only. Generated by `python -m src.forecast.tables`.", ""]
    for period, title in [("validation", "Validation 2017–2019 (never used for any choice)"),
                          ("recent", "Recent hindcast, 1 Jul – 12 Nov 2026 (unseen; live models only)")]:
        t = _load(period)
        n = t[t["lead"] == 1].iloc[0]
        storms = int(n["hits"] + n["misses"])
        days = int(n["hits"] + n["misses"] + n["false_alarms"] + n["correct_negatives"])
        sections += [f"## {title}", "", f"{storms} storm days out of {days}.", ""]
        for lead in config.FORECAST_LEADS:
            sections += [f"### Day {lead}", "", markdown(t, lead), ""]
    text = "\n".join(sections)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
    return text


if __name__ == "__main__":
    main()
